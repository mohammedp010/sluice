"""Evidence for ADR 0007: cancelling httpx mid-connect leaks connection-pool slots.

    python bench/httpx_pool_leak.py        # ~30 s, writes results/httpx-pool-leak.md

Fires batches of requests at a 50 ms mock upstream with tight time limits, two ways:
  cancel  the request runs inside asyncio.timeout (what Sluice's executor used to do)
  native  the limit is httpx's own Timeout (what the OpenAI-compatible adapter does now)
and counts pool entries left stuck in CONNECTING, then tries one normal request.
"""
from __future__ import annotations

import asyncio
import importlib.metadata as md
import sys
import tempfile
import time
from pathlib import Path

import httpx

sys.path.insert(0, str(Path(__file__).parent))
from compare import start, stop, wait_ready

PORT = 9011
ROUNDS = 6
OUT = Path(__file__).parent / "results"


async def trial(mode: str) -> list[str]:
    c = httpx.AsyncClient(base_url=f"http://127.0.0.1:{PORT}/v1",
                          timeout=httpx.Timeout(5, connect=5))
    body = {"model": "m", "messages": []}

    async def one(t: float) -> None:
        try:
            if mode == "native":
                await c.post("/chat/completions", json=body, timeout=httpx.Timeout(t))
            else:
                async with asyncio.timeout(t):
                    await c.post("/chat/completions", json=body)
        except (TimeoutError, httpx.HTTPError):
            pass

    rows = []
    for rnd in range(ROUNDS):
        for t in (0.001, 0.003, 0.01, 0.03, 0.06):
            await asyncio.gather(*[one(t) for _ in range(300)])
        stuck = sum("CONNECTING" in repr(x) for x in c._transport._pool.connections)
        rows.append(f"| {mode} | {rnd + 1} | {stuck} |")
    t0 = time.time()
    try:
        r = await c.post("/chat/completions", json=body)
        after = f"{r.status_code} in {time.time() - t0:.2f}s"
    except httpx.HTTPError as e:
        after = f"**{type(e).__name__}** after {time.time() - t0:.1f}s"
    await c.aclose()
    rows.append(f"| {mode} | then one normal request | {after} |")
    return rows


def main() -> None:
    tmp = Path(tempfile.mkdtemp(prefix="pool-leak-"))
    mock = start([sys.executable, str(Path(__file__).parent / "mock_upstream.py"),
                  "--port", str(PORT), "--latency-ms", "50"], tmp / "mock.log")
    try:
        wait_ready(f"http://127.0.0.1:{PORT}/v1/models")
        rows = asyncio.run(trial("cancel")) + asyncio.run(trial("native"))
    finally:
        stop(mock)
    md_ = ["# httpx connection-pool leak under cancellation", "",
           (f"Generated by `bench/httpx_pool_leak.py`: httpx {md.version('httpx')}, httpcore "
            f"{md.version('httpcore')}, anyio {md.version('anyio')}. Each round sends 5 x 300 "
            "requests with limits from 1 to 60 ms at a 50 ms upstream. Pool limit: 100."), "",
           "| timeouts | round | pool entries stuck in CONNECTING |", "|---|---|---|", *rows, "",
           ("Cancelling the task (`asyncio.timeout`) mid-connect strands pool entries for good; "
            "httpx's own timeouts clean up. See ADR 0007 for what this did to Sluice under load.")]
    OUT.mkdir(exist_ok=True)
    (OUT / "httpx-pool-leak.md").write_text("\n".join(md_) + "\n")
    print("\n".join(md_))


if __name__ == "__main__":
    main()
