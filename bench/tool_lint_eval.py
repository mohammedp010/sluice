"""C2's description lint (ADR 0011): false positives on real servers, recall on poisoned text.

    python bench/tool_lint_eval.py

Benign: every tool and parameter description in seven MCP reference servers
(bench/data/tool_descriptions_benign.jsonl, made by bench/tool_corpus.py from source, not by
running them). Poisoned: a labelled synthetic set after published tool-poisoning patterns
(bench/data/tool_descriptions_poisoned.jsonl), including innocently phrased ones meant to get
through.

Each string is linted the way the gateway would see it: a tool description as the tool's
`description`, a parameter description inside its `inputSchema`. "Other tools" are the tool
names of the *other* reference servers, as if all seven were configured: the lint only knows
the servers in the policy. Writes bench/results/tool-lint-eval.{md,json}.
"""
from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

from sluice.mcp.pins import lint

ROOT = Path(__file__).parent
OUT = ROOT / "results"


def load(name: str) -> list[dict]:
    return [json.loads(line) for line in (ROOT / "data" / name).read_text().splitlines()]


def definition(row: dict) -> dict:
    name = row.get("tool") or "tool"
    if row["where"] == "tool":
        return {"name": name, "description": row["text"]}
    return {"name": name, "description": "", "inputSchema": {
        "type": "object", "properties": {"arg": {"type": "string", "description": row["text"]}}}}


def kinds(flags: list[str]) -> list[str]:
    return sorted({f.split(":")[0] for f in flags})


def main() -> None:
    benign, poisoned = load("tool_descriptions_benign.jsonl"), load("tool_descriptions_poisoned.jsonl")
    names = defaultdict(set)
    for r in benign:
        r["where"] = "tool" if r["kind"] == "tool" else "param"
        if r["kind"] == "tool" and r["tool"]:
            names[r["server"]].add(r["tool"])
    every = set().union(*names.values())

    for r in benign:
        r["flags"] = lint(definition(r), every - names[r["server"]])
    for r in poisoned:
        r["flags"] = lint(definition(r), every)

    fp = [r for r in benign if r["flags"]]
    fp_tool = [r for r in fp if r["where"] == "tool"]
    n_tool = sum(r["where"] == "tool" for r in benign)
    caught = [r for r in poisoned if r["flags"]]
    by_cat = defaultdict(lambda: [0, 0])
    for r in poisoned:
        by_cat[r["category"]][0] += bool(r["flags"])
        by_cat[r["category"]][1] += 1
    servers_held = sorted({r["server"] for r in fp_tool})
    tools_by_server = {s: len(n) for s, n in names.items()}

    summary = {
        "benign_strings": len(benign), "benign_flagged": len(fp),
        "benign_tool_descriptions": n_tool, "benign_tool_descriptions_flagged": len(fp_tool),
        "benign_flag_kinds": Counter(k for r in fp for k in kinds(r["flags"])),
        "poisoned": len(poisoned), "poisoned_flagged": len(caught),
        "recall_by_category": {c: f"{a}/{b}" for c, (a, b) in sorted(by_cat.items())},
        "poisoned_flag_kinds": Counter(k for r in caught for k in kinds(r["flags"])),
    }
    (OUT / "tool-lint-eval.json").write_text(json.dumps({
        "summary": summary,
        "benign_flagged": [{k: r[k] for k in ("server", "tool", "where", "text", "flags")} for r in fp],
        "poisoned": [{k: r[k] for k in ("id", "category", "where", "text", "flags")} for r in poisoned],
    }, indent=1, ensure_ascii=True))

    pct = lambda a, b: f"{100 * a / b:.0f}%" if b else "n/a"
    md = [
        "# Tool description lint: false positives and recall",
        "",
        ("Generated by `bench/tool_lint_eval.py` from `bench/data/tool_descriptions_benign.jsonl` "
        f"({len(benign)} strings from {len(names)} MCP reference servers, "
        f"{benign[0]['source']}) and `bench/data/tool_descriptions_poisoned.jsonl` "
        f"({len(poisoned)} labelled synthetic strings). No server was run: the benign strings "
        "were read from source by `bench/tool_corpus.py`."),
        "",
        ("> **Caveats.** The poisoned set was written by the same person who wrote the lint, after "
        "reading the same attack write-ups, so the explicit and hidden categories flatter it. The "
        "subtle category exists to show what it misses. The benign side is seven servers, mostly "
        "short descriptions; large third-party servers with long, link-heavy descriptions will "
        "trip the `url` and `long` flags more often. Every number here moves when the data does."),
        "",
        "## Result",
        "",
        (f"- **Benign tool descriptions flagged: {len(fp_tool)} of {n_tool} "
        f"({pct(len(fp_tool), n_tool)}).** In `auto_first` these tools would wait as pending "
        f"instead of being served. Servers affected: {', '.join(servers_held) or 'none'}."),
        (f"- Benign strings flagged overall (parameters and fields included): {len(fp)} of "
        f"{len(benign)} ({pct(len(fp), len(benign))})."),
        (f"- **Poisoned strings flagged: {len(caught)} of {len(poisoned)} "
        f"({pct(len(caught), len(poisoned))}).**"),
        "",
        "| poisoned category | flagged | what it is |",
        "|---|---|---|",
    ]
    about = {
        "explicit": "instruction blocks in plain sight (`<IMPORTANT>`, \"ignore previous\")",
        "hidden": "zero-width, tag-block or bidi characters, or the payload pushed out of view",
        "shadowing": "instructions about another server's tool",
        "param": "the payload in a parameter description",
        "subtle": "innocent wording: no keyword, path or URL",
    }
    for c, (a, b) in sorted(by_cat.items(), key=lambda x: list(about).index(x[0])):
        md.append(f"| {c} | {a}/{b} | {about[c]} |")
    md += ["", "Tools per reference server: " + ", ".join(
        f"{s} {n}" for s, n in sorted(tools_by_server.items())) + ".", "",
        "## Every benign string flagged", ""]
    if not fp:
        md.append("None.")
    else:
        md += ["| server | tool | where | flags | text |", "|---|---|---|---|---|"]
        for r in fp:
            text = r["text"].replace("\n", " ").replace("|", "\\|")
            text = text if len(text) <= 160 else text[:157] + "..."
            md.append(f"| {r['server']} | {r['tool'] or '-'} | {r['where']} | "
                      f"{'; '.join(r['flags']).replace('|', '/')} | {text} |")
    md += ["", "## Every poisoned string missed", ""]
    missed = [r for r in poisoned if not r["flags"]]
    if not missed:
        md.append("None.")
    else:
        md += ["| id | category | text |", "|---|---|---|"]
        for r in missed:
            md.append(f"| {r['id']} | {r['category']} | "
                      f"{json.dumps(r['text'])[1:-1].replace('|', '/')} |")
    (OUT / "tool-lint-eval.md").write_text("\n".join(md) + "\n")
    print("\n".join(md[md.index("## Result"):md.index("## Every benign string flagged")]))


if __name__ == "__main__":
    main()
