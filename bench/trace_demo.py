"""Phase 4 "done when": one failed-over request, explained end to end from its trace.

Primary is down (503s), so the gateway retries it, falls over to the backup, and bills the
backup's (fake) prices to the key's team. Writes:
  bench/results/trace-failover.md    span tree + the matching ledger row (readable)
  bench/results/trace-failover.json  raw spans (OTel JSON) for anything else to ingest

With Jaeger running (docker compose up jaeger) add --otlp to also send the trace there,
then open http://localhost:16686 and search for the printed trace id.
"""
from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

import httpx
from opentelemetry.sdk.trace.export import SimpleSpanProcessor
from opentelemetry.sdk.trace.export.in_memory_span_exporter import InMemorySpanExporter

from sluice.api.app import create_app
from sluice.auth.keys import KeyStore
from sluice.config import Settings
from sluice.limits.state import MemoryState
from sluice.providers.mock import MockProvider
from sluice.telemetry.ledger import UsageLedger
from sluice.telemetry.otel import build_telemetry

OUT = Path(__file__).parent / "results"
SHOW = ("gen_ai.request.model", "gen_ai.response.model", "gen_ai.provider.name", "error.type",
        "sluice.attempt", "sluice.team", "sluice.app", "sluice.provider", "sluice.outcome",
        "sluice.attempts", "sluice.fallbacks", "gen_ai.usage.input_tokens",
        "gen_ai.usage.output_tokens", "sluice.cost_usd", "sluice.tokens.estimate",
        "http.response.status_code")


def tree(spans) -> list[str]:
    t0 = min(s.start_time for s in spans)
    kids: dict[int | None, list] = {}
    for s in sorted(spans, key=lambda s: s.start_time):
        kids.setdefault(s.parent.span_id if s.parent else None, []).append(s)
    lines: list[str] = []

    def walk(s, depth):
        attrs = ", ".join(f"{k}={s.attributes[k]}" for k in SHOW if k in s.attributes)
        status = " ERROR" if s.status.status_code.name == "ERROR" else ""
        lines.append(f"{'  ' * depth}- {s.name} [{s.kind.name.lower()}{status}] "
                     f"+{(s.start_time - t0) / 1e6:.1f}ms {(s.end_time - s.start_time) / 1e6:.1f}ms"
                     f"  {attrs}")
        for e in s.events:
            lines.append(f"{'  ' * depth}  * event {e.name}: {dict(e.attributes)}")
        for c in kids.get(s.context.span_id, []):
            walk(c, depth + 1)

    for root in kids[None]:
        walk(root, 0)
    return lines


async def main(otlp: bool):
    spans = InMemorySpanExporter()
    tel = build_telemetry(service_name="sluice-demo", span_exporter=spans)
    if otlp:
        from opentelemetry.exporter.otlp.proto.http.trace_exporter import OTLPSpanExporter
        tel.tracer_provider.add_span_processor(SimpleSpanProcessor(OTLPSpanExporter(
            endpoint="http://localhost:4318/v1/traces")))
    settings = Settings(
        providers={"primary": {"type": "mock"}, "backup": {"type": "mock"}},
        routes={"chat-default": {"deadline_s": 5, "chain": [
            {"provider": "primary", "upstream_model": "big-model", "retries": 1},
            {"provider": "backup", "upstream_model": "small-model", "retries": 0,
             "price_in_per_mtok": 0.15, "price_out_per_mtok": 0.60}]}})
    keys, ledger = KeyStore(":memory:"), UsageLedger(":memory:")
    raw, _ = keys.create("demo", team="search", app="web")
    app = create_app(
        settings,
        {"primary": MockProvider("primary", error_rate=1.0, error_status=503, latency_ms=30),
         "backup": MockProvider("backup", latency_ms=40, tokens_per_sec=200,
                                text="Paris is the capital of France.")},
        state=MemoryState(), keystore=keys, telemetry=tel, ledger=ledger)
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://t",
                                 headers={"Authorization": f"Bearer {raw}"}) as c:
        r = await c.post("/v1/chat/completions", json={
            "model": "chat-default",
            "messages": [{"role": "user", "content": "What is the capital of France?"}]})
    tid = r.headers["x-sluice-trace-id"]
    row = ledger.by_trace(tid)
    tel.shutdown()

    finished = spans.get_finished_spans()
    md = [
        "# A failed-over request, explained by its trace",
        "",
        "Generated by `bench/trace_demo.py` (mock upstreams, $0). Primary returns 503, so the",
        "gateway retries it once, falls over to the backup and bills the backup's prices.",
        "",
        (f"HTTP {r.status_code}, `x-sluice-provider: {r.headers['x-sluice-provider']}`, "
         f"`x-sluice-trace-id: {tid}`"),
        "",
        "## Span tree",
        "```",
        *tree(finished),
        "```",
        "",
        "## Ledger row for this trace (`python -m sluice.report --trace <id>`)",
        "```",
        *[f"{k:>18}: {v}" for k, v in row.items() if k not in ("id", "ts")],
        "```",
    ]
    OUT.mkdir(exist_ok=True)
    (OUT / "trace-failover.md").write_text("\n".join(md) + "\n")
    (OUT / "trace-failover.json").write_text(
        json.dumps([json.loads(s.to_json()) for s in finished], indent=2) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    asyncio.run(main("--otlp" in sys.argv))
